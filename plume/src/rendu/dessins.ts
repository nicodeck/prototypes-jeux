// Tous les dessins du jeu, en texte : une lettre par pixel (voir palette.ts), « . » = transparent.

export type Dessin = string[];

/** Lit un dessin écrit sur plusieurs lignes, en ignorant l'indentation. */
export function d(texte: string): Dessin {
  const lignes = texte.split("\n").map((l) => l.trim()).filter((l) => l.length > 0);
  for (const l of lignes) {
    if (l.length !== lignes[0].length) throw new Error(`Dessin mal formé : « ${l} »`);
  }
  return lignes;
}

const vide = (largeur: number, n: number): Dessin => Array(n).fill(".".repeat(largeur));
const remplacer = (dessin: Dessin, debut: number, lignes: Dessin) => dessin.map((l, i) => lignes[i - debut] ?? l);
const decaler = (dessin: Dessin, dy: number): Dessin =>
  dy < 0 ? [...dessin.slice(-dy), ...vide(dessin[0].length, -dy)] : [...vide(dessin[0].length, dy), ...dessin.slice(0, dessin.length - dy)];

