const ACCENTS: Record<string, [string, string[]]> = {
  É: ["E", ["..#.", ".#.."]], È: ["E", [".#..", "..#."]], Ê: ["E", [".##.", "#..#"]], À: ["A", [".#..", "..#."]],
  Â: ["A", [".##.", "#..#"]], Ô: ["O", [".##.", "#..#"]], Î: ["I", [".#.", "#.#"]], Ù: ["U", [".#..", "..#."]],
  Û: ["U", [".##.", "#..#"]], Ç: ["C", []], Œ: ["O", []],
};

export type Glyphe = { largeur: number; pixels: [number, number][] };

function glyphe(base: string, accent: string[] = [], cedille = false): Glyphe {
  const lignes = base.split("/");
  const pixels: [number, number][] = [];
  lignes.forEach((l, y) => [...l].forEach((c, x) => c === "#" && pixels.push([x, y + 2])));
  accent.forEach((l, y) => [...l].forEach((c, x) => c === "#" && pixels.push([x, y])));
  if (cedille) pixels.push([2, 7]);
  return { largeur: lignes[0].length, pixels };
}

export const GLYPHES = new Map<string, Glyphe>();
for (const [c, motif] of Object.entries(L)) GLYPHES.set(c, glyphe(motif));
for (const [c, [base, accent]] of Object.entries(ACCENTS)) GLYPHES.set(c, glyphe(L[base], accent, c === "Ç"));
GLYPHES.set("Œ", { largeur: 6, pixels: glyphe(".####/#.#../#.###/#.#../.####").pixels });
GLYPHES.set("'", glyphe(L["'"]));
