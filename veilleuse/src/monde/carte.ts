// La mine, salle par salle, une lettre par case (une case = 16 pixels).
//
//   #  roche              =  planche (on la traverse par-dessous, ↓ pour descendre)
//   ~  eau                H  départ de Veilleuse
//   L  lanterne éteinte   C  le Cœur, tout au fond
//   *  cristal            !  chaîne qui pend du plafond jusqu'à cette case
//   |  étai en bois       w  wagonnet abandonné
//   R  rai de lumière qui tombe d'une fissure
//
// Chaque salle est posée dans la mine à sa colonne et sa ligne. Deux salles voisines se
// touchent : une ouverture sur le bord de l'une doit continuer sur le bord de l'autre.
// Une ligne plus courte que la salle est complétée par de la roche.
//
// Après une modification, `bun test` vérifie que tout reste atteignable depuis le départ.

